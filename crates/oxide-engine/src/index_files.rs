    #[test]
    fn splits_and_renders_yaml() {
        let (manual, generated) = split_yaml("indexes:\r\n  # AUTOGENERATED \n- kind: K");
        assert_eq!(manual, "indexes:\n");
        assert_eq!(
            generated.as_deref(),
            Some("  # AUTOGENERATED \n- kind: K\n")
        );
        let defs = parse_yaml("indexes:\n- kind: K\n  ancestor: yes\n  properties:\n  - name: a\n  - name: b\n    direction: desc\n").unwrap();
        assert_eq!(
            defs[0].yaml(),
            "- kind: \"K\"\n  ancestor: yes\n  properties:\n  - name: \"a\"\n  - name: \"b\"\n    direction: desc\n"
        );
        assert!(parse_yaml("indexes:\n- kind: K\n  bogus: 1\n").is_err());
    }
