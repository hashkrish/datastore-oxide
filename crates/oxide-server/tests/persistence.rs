//! Durability of the on-disk store beyond what the Java comparison covers: a killed process keeps
//! what was saved, SIGTERM saves, the periodic save runs, and an unreadable store is moved aside
//! rather than overwritten.

use std::io::{BufRead, BufReader};
use std::path::Path;
use std::process::{Child, Command, Stdio};
use std::time::Duration;

struct Emulator {
    child: Child,
    base: String,
}

impl Drop for Emulator {
    fn drop(&mut self) {
        let _ = self.child.kill();
    }
}

fn start(dir: &Path, envs: &[(&str, &str)]) -> Emulator {
    let mut child = Command::new(env!("CARGO_BIN_EXE_datastore-oxide"))
        .args(["start", "--port=0", "--consistency=1.0"])
        .arg(dir)
        .env("OXIDE_LOG", "off")
        .envs(envs.iter().copied())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    let mut lines = BufReader::new(child.stdout.take().unwrap()).lines();
    let first = lines.next().unwrap().unwrap();
    let port: u16 = first.rsplit(':').next().unwrap().parse().unwrap();
    std::thread::spawn(move || lines.for_each(drop));
    Emulator {
        child,
        base: format!("http://127.0.0.1:{port}"),
    }
}

fn post(base: &str, path: &str, body: &str) -> (u16, String) {
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .http_status_as_error(false)
        .build()
        .into();
    let mut r = agent
        .post(format!("{base}{path}"))
        .header("content-type", "application/json")
        .send(body)
        .unwrap();
    (r.status().as_u16(), r.body_mut().read_to_string().unwrap())
}

fn put(base: &str, name: &str) {
    let body = format!(
        r#"{{"mode":"NON_TRANSACTIONAL","mutations":[{{"upsert":{{"key":{{"path":[{{"kind":"K","name":"{name}"}}]}}}}}}]}}"#
    );
    assert_eq!(post(base, "/v1/projects/p:commit", &body).0, 200);
}

fn found(base: &str, name: &str) -> bool {
    let body = format!(r#"{{"keys":[{{"path":[{{"kind":"K","name":"{name}"}}]}}]}}"#);
    post(base, "/v1/projects/p:lookup", &body)
        .1
        .contains("\"found\"")
}

fn project_dir(name: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("oxide-persist-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("WEB-INF")).unwrap();
    std::fs::write(
        dir.join("WEB-INF/index.yaml"),
        "indexes:\n# AUTOGENERATED\n",
    )
    .unwrap();
    dir
}

fn store(dir: &Path) -> std::path::PathBuf {
    dir.join("WEB-INF/appengine-generated/oxide_db.bin")
}

#[test]
fn killed_process_keeps_saved_data_only() {
    let dir = project_dir("kill");
    let mut e = start(&dir, &[]);
    put(&e.base, "saved");
    assert_eq!(post(&e.base, "/persist", "").0, 200);
    put(&e.base, "unsaved");
    e.child.kill().unwrap();
    e.child.wait().unwrap();
    let e = start(&dir, &[]);
    assert!(found(&e.base, "saved"));
    assert!(!found(&e.base, "unsaved"));
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn sigterm_saves() {
    let dir = project_dir("term");
    let mut e = start(&dir, &[]);
    put(&e.base, "a");
    let pid = e.child.id().to_string();
    assert!(
        Command::new("kill")
            .args(["-TERM", &pid])
            .status()
            .unwrap()
            .success()
    );
    e.child.wait().unwrap();
    let e = start(&dir, &[]);
    assert!(found(&e.base, "a"));
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn saves_periodically() {
    let dir = project_dir("periodic");
    let mut e = start(&dir, &[("OXIDE_STORE_DELAY_MS", "100")]);
    put(&e.base, "a");
    let deadline = std::time::Instant::now() + Duration::from_secs(10);
    while !store(&dir).exists() {
        assert!(std::time::Instant::now() < deadline, "store never saved");
        std::thread::sleep(Duration::from_millis(50));
    }
    e.child.kill().unwrap();
    e.child.wait().unwrap();
    let e = start(&dir, &[]);
    assert!(found(&e.base, "a"));
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn unreadable_store_is_moved_aside() {
    let dir = project_dir("unreadable");
    std::fs::create_dir_all(store(&dir).parent().unwrap()).unwrap();
    std::fs::write(store(&dir), b"\xac\xed\x00\x05 not ours").unwrap();
    let e = start(&dir, &[]);
    assert!(!found(&e.base, "a"));
    put(&e.base, "a");
    assert_eq!(post(&e.base, "/persist", "").0, 200);
    let kept: Vec<_> = std::fs::read_dir(store(&dir).parent().unwrap())
        .unwrap()
        .filter_map(|e| e.ok()?.file_name().into_string().ok())
        .filter(|n| n.starts_with("oxide_db.bin.unreadable-"))
        .collect();
    assert_eq!(kept.len(), 1);
    let moved = store(&dir).with_file_name(&kept[0]);
    assert_eq!(std::fs::read(moved).unwrap(), b"\xac\xed\x00\x05 not ours");
    drop(e);
    std::fs::remove_dir_all(&dir).unwrap();
}
