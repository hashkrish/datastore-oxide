//! Replays every case recorded from the Java emulator (`tests/golden/cli`, see
//! `tools/record-cli-goldens.sh`) against our binary and compares stdout, exit code and the
//! files left in the scratch directory.

use std::path::{Path, PathBuf};
use std::process::Command;

fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/golden/cli/java")
}

/// Same fixtures as `tools/record-cli-goldens.sh`.
fn fixtures() -> tempfile::TempDir {
    let tmp = tempfile::tempdir().unwrap();
    std::fs::create_dir_all(tmp.path().join("proj/WEB-INF")).unwrap();
    std::fs::write(
        tmp.path().join("proj/WEB-INF/index.yaml"),
        "indexes:\n# AUTOGENERATED\n",
    )
    .unwrap();
    std::fs::create_dir_all(tmp.path().join("nonempty")).unwrap();
    std::fs::write(tmp.path().join("nonempty/f"), "").unwrap();
    tmp
}

fn list_files(root: &Path) -> String {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            out.push(format!("./{}", path.strip_prefix(root).unwrap().display()));
            if path.is_dir() {
                walk(root, &path, out);
            }
        }
    }
    let mut out = Vec::new();
    walk(root, root, &mut out);
    out.sort();
    out.iter().map(|l| format!("{l}\n")).collect()
}

#[test]
fn cli_matches_java_goldens() {
    let dir = golden_dir();
    let mut cases: Vec<u32> = std::fs::read_dir(&dir)
        .unwrap()
        .filter_map(|e| {
            e.unwrap()
                .file_name()
                .to_str()?
                .strip_suffix(".args")?
                .parse()
                .ok()
        })
        .collect();
    cases.sort();
    assert!(!cases.is_empty(), "no goldens in {}", dir.display());

    let mut failures = Vec::new();
    for n in cases {
        let read = |ext: &str| std::fs::read_to_string(dir.join(format!("{n}.{ext}"))).unwrap();
        let line = read("args");
        let tmp = fixtures();
        let tmp_str = tmp.path().to_str().unwrap();
        let args: Vec<String> = line
            .split_whitespace()
            .map(|a| a.replace("$TMP", tmp_str))
            .collect();

        let output = Command::new(env!("CARGO_BIN_EXE_datastore-oxide"))
            .args(&args)
            .current_dir(tmp.path())
            .env("OXIDE_LOG", "off")
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&output.stdout).replace(tmp_str, "$TMP");
        let code = output.status.code().unwrap_or(-1);

        let want_code: i32 = read("rc").trim().parse().unwrap();
        let mut problems = Vec::new();
        if stdout != read("out") {
            problems.push(format!(
                "stdout differs:\n--- java\n{}--- oxide\n{stdout}",
                read("out")
            ));
        }
        if code != want_code {
            problems.push(format!("exit code {code}, java {want_code}"));
        }
        if list_files(tmp.path()) != read("files") {
            problems.push(format!(
                "files differ:\n--- java\n{}--- oxide\n{}",
                read("files"),
                list_files(tmp.path())
            ));
        }
        if !problems.is_empty() {
            failures.push(format!("[{n}] {}\n{}", line.trim(), problems.join("\n")));
        }
    }
    assert!(
        failures.is_empty(),
        "{} case(s) differ from Java:\n\n{}",
        failures.len(),
        failures.join("\n\n")
    );
}
