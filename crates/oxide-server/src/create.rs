//! The `create` action: lays out a project directory the way the Java emulator does.

use std::io::ErrorKind;
use std::path::Path;

use anyhow::{Context, Result};

use crate::cli::CreateConfig;

/// Contents the Java emulator writes to `WEB-INF/index.yaml` in a new project.
pub const INITIAL_INDEX_YAML: &str = "indexes:\n# AUTOGENERATED\n";

/// Runs `create`, printing to stdout like Java. Returns the process exit code.
pub fn run(cfg: &CreateConfig) -> Result<i32> {
    if cfg.project_id.is_some() {
        tracing::info!(
            "Provided project_id to Cloud Datastore emulator create command, which is no longer necessary."
        );
    }
    let dir = std::path::absolute(&cfg.directory)?;
    if is_non_empty_dir(&dir) {
        println!(
            "Project directory already exists and is non-empty: {}.\nExiting.",
            dir.display()
        );
        return Ok(1);
    }
    // Like Java's File.mkdir: parents are not created, and failures surface on the file write.
    let web_inf = dir.join("WEB-INF");
    let _ = std::fs::create_dir(&dir);
    let _ = std::fs::create_dir(&web_inf);
    let index = web_inf.join("index.yaml");
    std::fs::write(&index, INITIAL_INDEX_YAML)
        .with_context(|| format!("writing {}", index.display()))?;
    println!(
        "Created new Cloud Datastore project in '{}'.",
        dir.display()
    );
    Ok(0)
}

fn is_non_empty_dir(dir: &Path) -> bool {
    match std::fs::read_dir(dir) {
        Ok(mut entries) => entries.next().is_some(),
        Err(e) => e.kind() != ErrorKind::NotFound && dir.exists(),
    }
}
