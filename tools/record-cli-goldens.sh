#!/usr/bin/env bash
# Records the Java emulator's CLI behaviour (stdout + exit code) for every case in
# tests/golden/cli/cases.txt into tests/golden/cli/java/. Runs the jar in a JRE container.
#
# Usage: tools/record-cli-goldens.sh [path/to/cloud-datastore-emulator-dir]
#   Env: CONTAINER (podman|docker, default podman), JRE_IMAGE (default eclipse-temurin:21-jre)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EMU="${1:-$(dirname "$(dirname "$(command -v gcloud)")")/platform/cloud-datastore-emulator}"
CONTAINER="${CONTAINER:-podman}"
IMAGE="${JRE_IMAGE:-docker.io/library/eclipse-temurin:21-jre}"
OUT="$ROOT/tests/golden/cli/java"

rm -rf "$OUT"
mkdir -p "$OUT"
n=0
while IFS= read -r line; do
  [[ -z "$line" || "$line" == \#* ]] && continue
  n=$((n + 1))
  tmp="$(mktemp -d)"
  mkdir -p "$tmp/proj/WEB-INF" "$tmp/nonempty"
  printf 'indexes:\n# AUTOGENERATED\n' > "$tmp/proj/WEB-INF/index.yaml"
  touch "$tmp/nonempty/f"
  eval "set -- ${line//\$TMP/$tmp}"
  set +e
  timeout 60 "$CONTAINER" run --rm -v "$EMU:/emu:ro" -v "$tmp:$tmp:Z" -w "$tmp" "$IMAGE" \
    java -cp /emu/CloudDatastore.jar com.google.cloud.datastore.emulator.CloudDatastore "$@" \
    > "$OUT/$n.out" 2> /dev/null
  echo $? > "$OUT/$n.rc"
  set -e
  sed -i "s#$tmp#\$TMP#g" "$OUT/$n.out"
  printf '%s\n' "$line" > "$OUT/$n.args"
  (cd "$tmp" && find . -mindepth 1 | sort) > "$OUT/$n.files"
  rm -rf "$tmp"
  echo "[$n] rc=$(cat "$OUT/$n.rc") $line"
done < "$ROOT/tests/golden/cli/cases.txt"
